create table public.seasons (
  id bigint generated by default as identity primary key,
  season_key text not null unique,
  display_name text not null,
  final_gameweek smallint not null,
  archived_at timestamp with time zone,
  created_at timestamp with time zone not null default now(),
  constraint seasons_key_format_check
    check (season_key ~ '^[0-9]{2}-[0-9]{2}$'),
  constraint seasons_display_name_not_blank_check
    check (btrim(display_name) <> ''),
  constraint seasons_final_gameweek_check
    check (final_gameweek between 1 and 38)
);

create table public.season_results (
  id bigint generated by default as identity primary key,
  season_id bigint not null,
  team_name text not null,
  owner_display_name text not null,
  final_position smallint not null,
  final_score integer not null,
  constraint season_results_season_id_fkey
    foreign key (season_id)
    references public.seasons(id)
    on delete restrict,
  constraint season_results_team_name_not_blank_check
    check (btrim(team_name) <> ''),
  constraint season_results_owner_name_not_blank_check
    check (btrim(owner_display_name) <> ''),
  constraint season_results_final_position_check
    check (final_position > 0),
  constraint season_results_position_unique
    unique (season_id, final_position)
);

create table public.season_result_players (
  id bigint generated by default as identity primary key,
  season_result_id bigint not null,
  squad_order smallint not null,
  player_display_name text not null,
  position text not null,
  club_name text not null,
  club_short_name text not null,
  constraint season_result_players_result_id_fkey
    foreign key (season_result_id)
    references public.season_results(id)
    on delete restrict,
  constraint season_result_players_squad_order_check
    check (squad_order between 1 and 11),
  constraint season_result_players_name_not_blank_check
    check (btrim(player_display_name) <> ''),
  constraint season_result_players_position_check
    check (position in ('goalkeeper', 'defender', 'midfielder', 'forward')),
  constraint season_result_players_club_name_not_blank_check
    check (btrim(club_name) <> ''),
  constraint season_result_players_club_short_name_not_blank_check
    check (btrim(club_short_name) <> ''),
  constraint season_result_players_squad_order_unique
    unique (season_result_id, squad_order)
);

create table public.season_result_transfers (
  id bigint generated by default as identity primary key,
  season_result_id bigint not null,
  gameweek smallint not null,
  transfer_order smallint not null,
  outgoing_player_display_name text not null,
  outgoing_club_name text not null,
  outgoing_club_short_name text not null,
  incoming_player_display_name text not null,
  incoming_club_name text not null,
  incoming_club_short_name text not null,
  constraint season_result_transfers_result_id_fkey
    foreign key (season_result_id)
    references public.season_results(id)
    on delete restrict,
  constraint season_result_transfers_gameweek_check
    check (gameweek between 1 and 38),
  constraint season_result_transfers_order_check
    check (transfer_order > 0),
  constraint season_result_transfers_outgoing_name_not_blank_check
    check (btrim(outgoing_player_display_name) <> ''),
  constraint season_result_transfers_outgoing_club_name_not_blank_check
    check (btrim(outgoing_club_name) <> ''),
  constraint season_transfers_out_club_short_not_blank_check
    check (btrim(outgoing_club_short_name) <> ''),
  constraint season_result_transfers_incoming_name_not_blank_check
    check (btrim(incoming_player_display_name) <> ''),
  constraint season_result_transfers_incoming_club_name_not_blank_check
    check (btrim(incoming_club_name) <> ''),
  constraint season_transfers_in_club_short_not_blank_check
    check (btrim(incoming_club_short_name) <> ''),
  constraint season_result_transfers_order_unique
    unique (season_result_id, transfer_order)
);

comment on table public.seasons is
  'Catalogue of league seasons. A non-null archived_at marks a completed immutable snapshot.';

comment on table public.season_results is
  'Final fantasy-team standings copied for display without private or operational team data.';

comment on table public.season_result_players is
  'Final Squad display snapshot independent of live FPL player and club identifiers.';

comment on table public.season_result_transfers is
  'Ordered outgoing-to-incoming transfer display snapshot independent of live FPL identifiers.';

create or replace function public.reject_archived_season_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if old.archived_at is not null then
    raise exception 'Archived Season snapshots are read-only';
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;

  return new;
end;
$$;

create or replace function public.reject_archived_snapshot_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  old_season_id bigint;
  new_season_id bigint;
begin
  if tg_table_name = 'season_results' then
    if tg_op <> 'INSERT' then
      old_season_id := old.season_id;
    end if;

    if tg_op <> 'DELETE' then
      new_season_id := new.season_id;
    end if;
  else
    if tg_op <> 'INSERT' then
      select sr.season_id
      into old_season_id
      from public.season_results sr
      where sr.id = old.season_result_id;
    end if;

    if tg_op <> 'DELETE' then
      select sr.season_id
      into new_season_id
      from public.season_results sr
      where sr.id = new.season_result_id;
    end if;
  end if;

  if exists (
    select 1
    from public.seasons s
    where s.id in (old_season_id, new_season_id)
      and s.archived_at is not null
  ) then
    raise exception 'Archived Season snapshots are read-only';
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;

  return new;
end;
$$;

create trigger reject_archived_season_change
before update or delete on public.seasons
for each row execute function public.reject_archived_season_change();

create trigger reject_archived_result_change
before insert or update or delete on public.season_results
for each row execute function public.reject_archived_snapshot_change();

create trigger reject_archived_player_change
before insert or update or delete on public.season_result_players
for each row execute function public.reject_archived_snapshot_change();

create trigger reject_archived_transfer_change
before insert or update or delete on public.season_result_transfers
for each row execute function public.reject_archived_snapshot_change();

