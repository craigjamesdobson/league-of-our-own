create policy "Completed Seasons are publicly readable"
on public.seasons
for select
using (archived_at is not null);

create policy "Completed Season Results are publicly readable"
on public.season_results
for select
using (
  exists (
    select 1
    from public.seasons s
    where s.id = season_results.season_id
      and s.archived_at is not null
  )
);

create policy "Completed Final Squads are publicly readable"
on public.season_result_players
for select
using (
  exists (
    select 1
    from public.season_results sr
    join public.seasons s on s.id = sr.season_id
    where sr.id = season_result_players.season_result_id
      and s.archived_at is not null
  )
);

create policy "Completed Season Transfers are publicly readable"
on public.season_result_transfers
for select
using (
  exists (
    select 1
    from public.season_results sr
    join public.seasons s on s.id = sr.season_id
    where sr.id = season_result_transfers.season_result_id
      and s.archived_at is not null
  )
);

